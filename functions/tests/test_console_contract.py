"""The console's view of the tool outputs: ``console/src/lib/tool-schemas.json`` is generated from the registry.

The console calls some tools directly through the Gateway and renders the schedule tools' results from the agent's
STATE_SNAPSHOT events (raw tool payloads). Its unit tests validate the console's types and mock fixtures against
this file, so a renamed or retyped output field fails on both sides. The schemas describe the wire format of
:func:`fast_channels.functions.tools.dispatch.handler`: ``ok: true`` plus ``model_dump(mode="json",
exclude_none=True)``, so a nullable field is optional and never ``null``.
"""

import json
from collections.abc import Mapping
from pathlib import Path
from typing import Any, Final

from pydantic import BaseModel

from fast_channels.functions.tools import registry

REPO: Final = Path(__file__).resolve().parents[2]
SCHEMAS: Final = REPO / "console/src/lib/tool-schemas.json"
CONSOLE_TOOLS: Final = (
    # called by the Channels and Library views
    "channels___list_channels",
    "channels___get_channel",
    "channels___start_channel",
    "channels___stop_channel",
    "library___find_assets",
    "encoding___list_ladders",
    # rendered from STATE_SNAPSHOT by the Assistant view
    "schedule___plan",
    "schedule___publish",
    "schedule___get_schedule",
)
_KEPT: Final = ("type", "enum", "const", "properties", "required", "items", "additionalProperties", "anyOf")


def wire_schema(model: type[BaseModel]) -> dict[str, Any]:
    """The JSON schema of a successful tool result with output model ``model``, every ``$ref`` inlined."""
    schema = model.model_json_schema(mode="serialization")
    body = _inline(schema, schema.get("$defs", {}))
    return {
        **body,
        "properties": {"ok": {"const": True}, **body["properties"]},
        "required": ["ok", *body["required"]],
    }


def render() -> str:
    specs = {spec.qualified_name: spec for spec in registry.all_tools()}
    document = {
        "$comment": "Generated by functions/tests/test_console_contract.py from the tool registry; do not edit.",
        "tools": {name: wire_schema(specs[name].output) for name in CONSOLE_TOOLS},
    }
    return json.dumps(document, indent=2, ensure_ascii=False) + "\n"


def _nullable(node: Mapping[str, Any]) -> bool:
    return any(variant.get("type") == "null" for variant in node.get("anyOf", ()))


def _inline(node: Mapping[str, Any], defs: Mapping[str, Any]) -> dict[str, Any]:
    if ref := node.get("$ref"):
        return _inline({**defs[ref.rsplit("/", 1)[-1]], **{k: v for k, v in node.items() if k != "$ref"}}, defs)
    if variants := node.get("anyOf"):
        concrete = [v for v in variants if v.get("type") != "null"]  # exclude_none: null never reaches the wire
        if len(concrete) == 1:
            return _inline({**concrete[0], **{k: v for k, v in node.items() if k != "anyOf"}}, defs)
        node = {**node, "anyOf": concrete}
    out: dict[str, Any] = {}
    for key in _KEPT:
        match key, node.get(key):
            case _, None:
                continue
            case "properties", properties:
                out[key] = {name: _inline(child, defs) for name, child in properties.items()}
                out["required"] = [name for name, child in properties.items() if not _nullable(child)]
            case "required", _:
                continue  # recomputed with the properties: a field is absent exactly when it is None
            case "items" | "additionalProperties", dict() as child:
                out[key] = _inline(child, defs)
            case "anyOf", variants:
                out[key] = [_inline(variant, defs) for variant in variants]
            case _, value:
                out[key] = value
    return out


def test_console_tool_schemas_are_current() -> None:
    text = render()
    if not SCHEMAS.exists() or SCHEMAS.read_text() != text:
        SCHEMAS.write_text(text)
        raise AssertionError(f"{SCHEMAS.relative_to(REPO)} was stale and has been regenerated: review and commit it")


def test_console_tools_exist_and_return_objects() -> None:
    specs = {spec.qualified_name: spec for spec in registry.all_tools()}
    for name in CONSOLE_TOOLS:
        schema = wire_schema(specs[name].output)
        assert schema["type"] == "object" and "ok" in schema["required"], name


def test_wire_schema_makes_nullable_fields_optional_and_inlines_models() -> None:
    class Inner(BaseModel):
        value: int

    class Output(BaseModel):
        name: str
        note: str | None = None
        inner: Inner | None = None
        items: list[Inner] = []
        mapping: dict[str, Inner]

    schema = wire_schema(Output)

    assert schema["required"] == ["ok", "name", "items", "mapping"]
    assert schema["properties"]["note"] == {"type": "string"}
    inner = {"type": "object", "properties": {"value": {"type": "integer"}}, "required": ["value"]}
    assert schema["properties"]["inner"] == inner
    assert schema["properties"]["items"] == {"type": "array", "items": inner}
    assert schema["properties"]["mapping"] == {"type": "object", "additionalProperties": inner}

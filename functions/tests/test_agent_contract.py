"""The agent's view of the tools: its instructions name real tools and its conformance suite serves real definitions.

``agent/src/fast_channels/agent/evals/gateway_tools.json`` holds the Gateway tool definitions (description and
input schema, exactly as ``registry.gateway_tool_schema`` renders them) of the tools the offline eval serves, so
``scripts/eval_model.py`` measures the model against what it reads in production. The agent package cannot import
the registry (it does not depend on core), hence the generated file.
"""

import inspect
import json
import re
from pathlib import Path
from typing import Final

from fast_channels.agent.evals import fake_tools, runner
from fast_channels.functions.tools import registry

REPO: Final = Path(__file__).resolve().parents[2]
AGENT: Final = REPO / "agent/src/fast_channels/agent"
INSTRUCTIONS: Final = (*sorted((AGENT / "skills").glob("*/SKILL.md")), AGENT / "prompts/system.md")
TOOL_NAME: Final = re.compile(r"\b[a-z]+___[a-z_]+\b")


def render() -> str:
    specs = {spec.qualified_name: spec for spec in registry.all_tools()}
    definitions = [{**registry.gateway_tool_schema(specs[name]), "name": name} for name in fake_tools.TOOLS]
    document = {
        "$comment": "Generated by functions/tests/test_agent_contract.py from the tool registry; do not edit.",
        "tools": definitions,
    }
    return json.dumps(document, indent=2, ensure_ascii=False) + "\n"


def test_eval_gateway_definitions_are_current() -> None:
    text = render()
    if not fake_tools.DEFINITIONS.exists() or fake_tools.DEFINITIONS.read_text() != text:
        fake_tools.DEFINITIONS.write_text(text)
        raise AssertionError(f"{fake_tools.DEFINITIONS.relative_to(REPO)} was stale and has been regenerated")


def test_fake_tools_take_exactly_the_real_arguments() -> None:
    specs = {spec.qualified_name: spec for spec in registry.all_tools()}
    for name, method in fake_tools.TOOLS.items():
        real = set(registry.gateway_tool_schema(specs[name])["inputSchema"]["properties"]) - {"correlation_id"}
        fake = set(inspect.signature(getattr(fake_tools.FakeScheduleTools, method)).parameters) - {"self"}
        assert fake == real, name


def test_the_eval_asks_approval_for_exactly_the_registry_confirm_tools() -> None:
    assert set(registry.confirm_tools()) & fake_tools.TOOLS.keys() == runner.CONFIRM_TOOLS


def test_agent_instructions_and_console_name_only_real_tools() -> None:
    known = {spec.qualified_name for spec in registry.all_tools()}
    console = [path for path in sorted((REPO / "console/src").rglob("*.ts*")) if ".test." not in path.name]
    sources = [*INSTRUCTIONS, *console]
    for path in sources:
        unknown = set(TOOL_NAME.findall(path.read_text())) - known
        assert not unknown, f"{path.relative_to(REPO)} names unknown tools {sorted(unknown)}"
    assert {name for path in INSTRUCTIONS for name in TOOL_NAME.findall(path.read_text())} >= {
        "schedule___plan",
        "schedule___publish",
        "encoding___propose_ladder",
        "encoding___provision_ladder",
        "channels___create_channel",
    }

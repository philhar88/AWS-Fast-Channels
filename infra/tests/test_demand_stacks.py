"""The demand module's repository stacks (``modules.demand``): DemandEdge (the origin gate) and DemandBuild (the image
build and the guidance's bootstrap policy). The guidance itself deploys as its own app (scripts/prebid_guidance.py)."""

import json
import re
from collections.abc import Callable
from typing import TYPE_CHECKING, Any

import pytest

from fast_channels.infra.constructs.demand.guidance_bootstrap import POLICY_FILE, policy_document

if TYPE_CHECKING:
    from syrupy.assertion import SnapshotAssertion

type GetDeployment = Callable[..., Any]

DEMAND = {"prefix": "fastm", "modules.ops.enabled": True, "modules.demand.enabled": True}


def resources(template: Any, kind: str) -> list[dict[str, Any]]:
    return [r["Properties"] for r in template.find_resources(kind).values()]


@pytest.mark.parametrize("stack", ["demand_edge", "demand_build"])
def test_template_snapshot(
    deployment: GetDeployment, normalized: Callable[..., Any], snapshot_json: SnapshotAssertion, stack: str
) -> None:
    d = deployment(DEMAND)

    assert normalized(d.template(getattr(d.stage, stack))) == snapshot_json


def test_the_stacks_exist_only_with_the_module(deployment: GetDeployment) -> None:
    off = deployment({"prefix": "fastm"}).stage
    on = deployment(DEMAND).stage

    assert (off.demand_edge, off.demand_build) == (None, None)
    assert (on.demand_edge.stack_name, on.demand_edge.region) == ("FastChannels-fastm-DemandEdge", "us-east-1")
    assert on.demand_build.stack_name == "FastChannels-fastm-DemandBuild"
    assert not on.demand_edge.dependencies
    assert not on.demand_build.dependencies


def test_the_origin_gate_stays_in_us_east_1_whatever_the_region(deployment: GetDeployment) -> None:
    stage = deployment({**DEMAND, "agent.enabled": False}, region="eu-west-1").stage

    assert (stage.demand_edge.stack_name, stage.demand_edge.region) == (
        "FastChannels-fastm-DemandEdge-eu-west-1",
        "us-east-1",
    )
    assert stage.demand_build.region == "eu-west-1"


def test_the_rule_group_requires_an_origin_secret_on_auctions(deployment: GetDeployment) -> None:
    d = deployment(DEMAND)
    template = d.template(d.stage.demand_edge)
    [group] = resources(template, "AWS::WAFv2::RuleGroup")
    rules = {rule["Name"]: rule for rule in group["Rules"]}

    assert (group["Name"], group["Scope"], group["Capacity"]) == ("fastm-demand-origin", "CLOUDFRONT", 50)
    assert list(rules) == ["fast-origin-required", "fast-paths", "fast-rate"]
    assert all(rule["Action"] == {"Block": {}} for rule in rules.values())
    path, not_secret = rules["fast-origin-required"]["Statement"]["AndStatement"]["Statements"]
    assert path["ByteMatchStatement"]["SearchString"] == "/openrtb2/"
    secrets = not_secret["NotStatement"]["Statement"]["OrStatement"]["Statements"]
    assert [s["ByteMatchStatement"]["FieldToMatch"] for s in secrets] == [
        {"SingleHeader": {"Name": "x-fast-origin"}}
    ] * 2
    open_paths = rules["fast-paths"]["Statement"]["NotStatement"]["Statement"]["OrStatement"]["Statements"]
    assert [s["ByteMatchStatement"]["SearchString"] for s in open_paths] == ["/openrtb2/auction", "/status"]
    rate = rules["fast-rate"]["Statement"]["RateBasedStatement"]
    assert (rate["Limit"], rate["AggregateKeyType"], rate["EvaluationWindowSec"]) == (20000, "IP", 60)


def test_no_secret_value_is_in_a_template(deployment: GetDeployment) -> None:
    """The rule group reads both secrets through dynamic references; the secrets are generated by Secrets Manager."""
    d = deployment(DEMAND)
    template = d.template(d.stage.demand_edge)
    text = json.dumps(template.to_json())

    assert text.count("{{resolve:secretsmanager:") == 2
    assert [s["Name"] for s in resources(template, "AWS::SecretsManager::Secret")] == [
        "fastm/demand/origin-a",
        "fastm/demand/origin-b",
    ]
    assert all("SecretString" not in s for s in resources(template, "AWS::SecretsManager::Secret"))


def test_the_rate_limit_follows_the_configuration(deployment: GetDeployment) -> None:
    d = deployment({**DEMAND, "modules.demand.rate_limit_per_ip": 1234})
    [group] = resources(d.template(d.stage.demand_edge), "AWS::WAFv2::RuleGroup")

    assert group["Rules"][2]["Statement"]["RateBasedStatement"]["Limit"] == 1234


def test_the_image_is_built_on_x86_into_an_immutable_repository(deployment: GetDeployment) -> None:
    d = deployment(DEMAND)
    template = d.template(d.stage.demand_build)
    [repository] = resources(template, "AWS::ECR::Repository")
    [project] = resources(template, "AWS::CodeBuild::Project")

    assert (repository["RepositoryName"], repository["ImageTagMutability"]) == ("fastm-pbs", "IMMUTABLE")
    assert repository["ImageScanningConfiguration"] == {"ScanOnPush": True}
    assert project["Name"] == "fastm-pbs-image"
    assert project["Environment"]["Type"] == "LINUX_CONTAINER"  # x86 (ARM_CONTAINER on arm64)
    assert project["Environment"]["PrivilegedMode"] is True
    assert project["Source"]["Type"] == "NO_SOURCE"  # each build gets its context as a source override
    assert "bash build-image.sh" in project["Source"]["BuildSpec"]


def test_the_guidance_execution_policy_scopes_iam_s3_and_lambda_to_the_guidance(deployment: GetDeployment) -> None:
    d = deployment(DEMAND)
    [policy] = resources(d.template(d.stage.demand_build), "AWS::IAM::ManagedPolicy")
    statements = {s["Sid"]: s for s in policy["PolicyDocument"]["Statement"]}
    rendered = json.dumps(statements)

    assert policy["ManagedPolicyName"] == "fastm-guidance-cfn-exec"
    assert "iam:*" not in rendered
    assert "${" not in rendered  # every placeholder filled
    assert ":role/fastm-pbs*" in json.dumps(statements["GuidanceRolesOnly"]["Resource"])
    assert "AWSLambdaBasicExecutionRole" in json.dumps(statements["OnlyTheLambdaManagedPolicies"]["Condition"])
    assert "fastm-pbs*" in json.dumps(statements["GuidanceBucketsAndAssetsOnly"]["Resource"])
    assert "function:fastm-pbs*" in json.dumps(statements["GuidanceFunctionsOnly"]["Resource"])
    assert not {"kms:Decrypt", "kms:Encrypt", "kms:GenerateDataKey"} & set(
        statements["GuidanceKeysWithoutTheirData"]["Action"]
    )
    assert "parameter/cdk-bootstrap/fastm/*" in json.dumps(statements["BootstrapVersion"]["Resource"])


def test_the_policy_file_has_only_known_placeholders() -> None:
    placeholders = set(re.findall(r"\$\{[^}]+\}", POLICY_FILE.read_text()))

    assert placeholders == {"${Prefix}", "${Qualifier}", "${AWS::Partition}", "${AWS::AccountId}"}
    assert {s["Sid"] for s in policy_document("fastx")["Statement"]} >= {"GuidanceRolesOnly", "BootstrapVersion"}


